#!/usr/bin/env bash
# One entry point for local and CI verification. Browser mode builds pkg once.
set -euo pipefail
cd "$(dirname "$0")/.."
mode="${1:-all}"
if (($#)); then shift; fi
case "$mode" in native|browser|all) ;; *) echo 'Usage: scripts/verify.sh [native|browser|all] [browser options]' >&2; exit 2;; esac
wasm_profile="${VERIFY_WASM_PROFILE:-dev}"
case "$wasm_profile" in dev|release) ;; *) echo 'VERIFY_WASM_PROFILE must be dev or release' >&2; exit 2;; esac
if node scripts/verification-cache.mjs check "$mode" "$@"; then exit 0; fi
node scripts/verification-cache.mjs clear "$mode" "$@"
verification_key="$(node scripts/verification-cache.mjs key "$mode" "$@")"
mkdir -p output/verification
check() {
    local label="$1"; shift
    local log="output/verification/$label.log"
    if "$@" >"$log" 2>&1; then
        echo "PASS $label"
    else
        local status=$?
        echo "FAIL $label (full log: $log)" >&2
        tail -n 60 "$log" >&2
        return "$status"
    fi
}
if [[ "$mode" != browser ]]; then
    check rust-format cargo fmt --check
    check rust-tests cargo test --locked
    check rust-clippy cargo clippy --locked --all-targets -- -D warnings
    check sdk npm run test:sdk
    check harness npm run test:harness
    check xr-platform npm run test:xr
fi
if [[ "$mode" != native ]]; then
    (
    export RUSTFLAGS="${RUSTFLAGS:+$RUSTFLAGS }--cfg=web_sys_unstable_apis"
    check wasm-check cargo check --locked --target wasm32-unknown-unknown
    check wasm-clippy cargo clippy --locked --target wasm32-unknown-unknown -- -D warnings
    if node --input-type=module -e 'import {assertFreshBuild} from "./scripts/build-fingerprint.mjs"; await assertFreshBuild();' >/dev/null 2>&1; then
        echo 'WASM build reused: matching source and generated bytes'
    else
        if [[ "$wasm_profile" == release ]]; then
            check wasm-build wasm-pack build --target web --release -- --locked
        else
            check wasm-build wasm-pack build --target web --dev -- --locked
        fi
        node scripts/build-fingerprint.mjs --write
    fi
    )
fi
check types npm run typecheck
if [[ "$mode" != native ]]; then
    node scripts/test-browser.mjs "$@"
fi
node scripts/verification-cache.mjs record "$mode" "$verification_key" "$@"
