import {initEngine,installRuntimeInfo} from '../examples/shared/runtime-info.js';
import {VR_DEBUG_PANEL_OFFSET} from '../examples/shared/vr-debug-panel.js';
import {installXRSimulator} from './xr/simulator.js';
import {XRTestRun,publishXRReport} from './xr/testkit.js';
import {assertChanged} from './pixels.js';
const sim=installXRSimulator({profile:{id:'runtime-info',hz:72,eyeWidth:320,eyeHeight:320},clockTimers:false});
const run=new XRTestRun('runtime-info',sim,publishXRReport);
let engine;
await run.execute(async test=>{
    const canvas=document.querySelector('#gpu-canvas');
    engine=await initEngine(canvas,{backend:'webgl'});
    document.documentElement.dataset.rendererBackend=engine.renderer_backend();
    engine.resize(320,240);engine.set_render_effects(false,false);engine.setDebugOverlay(false);
    const ui=installRuntimeInfo(engine),near=(a,b)=>a.every((v,i)=>Math.abs(v-b[i])<.003);
    test.assert(ui===installRuntimeInfo(engine),'installation is idempotent');
    test.assert(!engine.frameProfile().enabled,'expensive CPU/GPU profiling defaults off');
    test.assert(!document.querySelector('[data-runtime-info]'),'no desktop statistics panel blocks VR entry');
    test.assert(engine.xr.player.head.object===null,'no head binding before XR');
    await engine.xr.enter();
    const yaw=-Math.atan2(.9,1),pitch=-Math.atan2(1.25,Math.hypot(.9,1));
    const sp=Math.sin(pitch/2),cp=Math.cos(pitch/2),sy=Math.sin(yaw/2),cy=Math.cos(yaw/2);
    const frame=(head={})=>{sim.frame({head:{tracked:true,position:[0,1.6,0],orientation:[cy*sp,sy*cp,-sy*sp,cy*cp],...head}});test.assert(!engine.xr.lastError,'XR frame succeeds');};
    frame();frame();
    const panel=engine.xr.player.head.object,id=panel?.id;
    test.assert(Boolean(panel),'one native panel allocated on XR entry');
    test.assert(near(panel.meshInfo.position,VR_DEBUG_PANEL_OFFSET),'native panel uses shared floor offset');
    test.assert(near(panel.meshInfo.scale,[1,1,1]),'native panel is not mirrored');
    test.assert(!engine.debugStats().enabled,'screen-space overlay stays off');
    const left=sim.pixels('left'),right=sim.pixels('right');
    ui.setVisible(false);frame();
    test.assert(engine.xr.player.head.object===null&&panel.meshInfo.position[1]<-9000,'hide releases binding and hides geometry');
    assertChanged(left,sim.pixels('left'),'left-eye native information pixels',30);
    assertChanged(right,sim.pixels('right'),'right-eye native information pixels',30);
    ui.setVisible(true);frame();
    test.assert(engine.xr.player.head.object?.id===id,'show reuses the original native node');
    frame({orientation:[0,.6,0,.8],position:[.3,1.1,.2]});
    test.assert(near(panel.meshInfo.position,[1.2,.35,-.8]),'translation follows feet; gaze and crouching do not rotate or raise panel');
    frame({tracked:false});test.assert(panel.meshInfo.position[1]<-9000,'tracking loss hides panel');
    frame();test.assert(near(panel.meshInfo.position,VR_DEBUG_PANEL_OFFSET),'tracking recovery restores native panel');
    await engine.xr.exit();test.assert(engine.xr.player.head.object===null&&panel.meshInfo.position[1]<-9000,'exit hides panel');
    await engine.xr.enter();frame();test.assert(engine.xr.player.head.object?.id===id,'reentry reuses same panel');
    await engine.xr.exit();ui.dispose();test.assert(!panel.exists,'dispose removes owned native node');
    // Adopt a scene panel and preserve a different native attachment.
    const adopted=engine.scene.createInfoPanel('diagnostics'),toggle=document.createElement('input');toggle.type='checkbox';
    const adoptedUI=installRuntimeInfo(engine,{panel:adopted,toggle});
    await engine.xr.enter();frame();test.assert(engine.xr.player.head.object?.id===adopted.id,'existing scene panel is adopted without duplicate');
    const equipment=engine.scene.createCube([0,-10000,0]);engine.xr.player.bindHead(equipment);
    adoptedUI.setVisible(true);test.assert(engine.xr.player.head.object?.id===equipment.id,'visibility change respects another native slot owner');
    adoptedUI.setVisible(false);test.assert(engine.xr.player.head.object?.id===equipment.id,'hide never unbinds another attachment');
    engine.xr.player.bindHead(null);toggle.checked=true;toggle.dispatchEvent(new Event('change'));frame();
    test.assert(engine.xr.player.head.object?.id===adopted.id,'scene checkbox restores adopted diagnostics');
    await engine.xr.exit();adoptedUI.dispose();equipment.remove();
});
engine?.dispose();
