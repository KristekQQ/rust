import {initEngine} from '../js/engine.js';
import {createScene,startCombat} from '../examples/monster-room/scene.js';
import {installXRSimulator} from './xr/simulator.js';
import {XRTestRun,publishXRReport,pixelDifference} from './xr/testkit.js';
import {assertForeground} from './pixels.js';
const sim=installXRSimulator({profile:{id:'monster-combat-72',hz:72,eyeWidth:320,eyeHeight:320},clockTimers:false});
const run=new XRTestRun('monster-combat',sim,publishXRReport);
let engine;
await run.execute(async test=>{
    engine=await initEngine(document.querySelector('#gpu-canvas'),{backend:'webgl'});
    document.documentElement.dataset.rendererBackend=engine.renderer_backend();
    engine.set_render_effects(false,false);engine.set_grid_visible(false);engine.set_light_helpers_visible(false);
    const world=await createScene(engine.scene);
    engine.xr.player.configureLocomotion({...world.locomotion,marker:world.marker});
    startCombat(engine,world);
    const state=()=>engine.scene.meleeState;
    const initialId=state().id;
    let rejected=false;
    try{engine.scene.configureMelee({enemies:world.enemies,swords:[world.swords[0],world.swords[0]],spawns:world.enemies.map((_,index)=>world.layout.modelSpawns[index].position),bounds:world.layout.walkableBounds});}catch{rejected=true;}
    test.assert(rejected&&state().id===initialId,'invalid reconfiguration preserves running encounter');
    const frame=(input={})=>{sim.frame(input);test.assert(!engine.xr.lastError,'native melee XR frame succeeds',String(engine.xr.lastError));};
    await engine.xr.enter({resolutionScale:1});
    frame({head:{position:[0,1.6,0]},controllers:{left:{position:[-.6,1.4,-.1]},right:{position:[.6,1.4,-.1]}}});frame();
    test.assert(engine.xr.player.state.leftHand.object?.id===world.swords[0].id&&engine.xr.player.state.rightHand.object?.id===world.swords[1].id,'both hands equipped with actual sword meshes');
    test.assert(state().kills===0,'encounter starts with no kills');
    const firstPosition=state().position;
    for(let i=0;i<20;i++)frame({dt:50});
    test.assert(Math.hypot(state().position[0],state().position[2])<Math.hypot(firstPosition[0],firstPosition[2]),'enemy actually pursues tracked player');
    test.assert(world.enemies.filter(enemy=>enemy.info.playback?.playing).length===1,'exactly one visible enemy during pursuit');
    // Place authored models in a reachable test lane; same native API and real tracked blades.
    const setup=()=>engine.scene.configureMelee({enemies:world.enemies,swords:world.swords,spawns:[[0,0,-1.8],[0,0,-1.8],[0,0,-1.8]],bounds:world.layout.walkableBounds,obstacles:[]});
    setup();
    frame({controllers:{left:{position:[-2,1.3,-.8]},right:{position:[0,1.3,-.8]}}});
    for(let i=0;i<10;i++)frame();
    test.assert(state().kills===0,'stationary sword intersecting enemy does not kill');
    frame({controllers:{right:{tracked:false}}});
    frame({controllers:{right:{tracked:true,position:[.7,1.3,-.8]}}});
    test.assert(state().kills===0,'tracking reentry does not manufacture a slash');
    frame({controllers:{right:{position:[-.3,1.3,-.8]}}});
    test.assert(state().kills===0,'implausible continuous tracking jump does not kill');
    frame({controllers:{right:{tracked:false}}});
    frame({controllers:{right:{tracked:true,position:[.7,1.3,-.8]}}});
    const before=sim.pixels('left');assertForeground(before,'combat stereo left');assertForeground(sim.pixels('right'),'combat stereo right');
    const stereo=sim.pixels(),preview=document.querySelector('#stereo');
    preview.width=stereo.width;preview.height=stereo.height;preview.getContext('2d').putImageData(stereo,0,0);
    for(const x of [.5,.3,.1,-.1,-.3,-.5])frame({controllers:{right:{position:[x,1.3,-.8],buttons:[0,0,0,0,1,0]}}});
    test.assert(Math.abs(engine.xr.player.state.locomotion.timeScale-.15)<.001,'sword hits remain valid during teleport slow motion',engine.xr.player.state.locomotion);
    frame({controllers:{right:{buttons:[0,0,0,0,1,1]}}});
    frame({controllers:{right:{buttons:[0,0,0,0,0,0]}}});
    test.assert(state().kills===1,'real moving right sword defeats first enemy',state());
    const first=state().active;
    test.assert(world.enemies.filter(enemy=>enemy.info.playback?.playing).length===1,'death animation does not spawn another living enemy');
    for(let i=0;i<15;i++)frame({dt:50});
    test.assert(state().active===first,'next enemy waits while first dies');
    for(let i=0;i<70;i++)frame({dt:50});
    test.assert(state().active!==first&&state().kills===1,'next enemy arrives after death completes',state());
    test.assert(world.enemies.filter(enemy=>enemy.info.playback?.playing).length===1,'only next enemy remains visible');
    test.assert(pixelDifference(before,sim.pixels('left'))>30,'death and new opponent change real rendered pixels');
    frame({controllers:{left:{position:[.7,1.3,-.8]},right:{position:[2,1.3,-.8]}}});
    frame();
    for(const x of [.5,.3,.1,-.1,-.3,-.5])frame({controllers:{left:{position:[x,1.3,-.8]}}});
    test.assert(state().kills===2,'left sword also defeats enemy',state());
    await engine.xr.exit();await engine.xr.enter({resolutionScale:1});
    frame({head:{position:[0,1.6,0]},controllers:{left:{position:[-.3,1.3,-.8]},right:{position:[.3,1.3,-.8]}}});
    test.assert(state().kills===2,'session reentry preserves encounter without phantom hit');
    engine.scene.configureMelee(null);
    test.assert(state()===null,'explicit stop clears encounter');
    test.assert(world.enemies.every(enemy=>enemy.info.playback?.playing),'stop restores original models');
    await engine.xr.exit();
});
engine?.dispose();
